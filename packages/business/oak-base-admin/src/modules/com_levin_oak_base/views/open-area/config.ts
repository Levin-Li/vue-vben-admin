export function getOpenAreaDisplayNames(record: Record<string, any>) {
  const areaCodeList = Array.isArray(record.areaCodeList)
    ? record.areaCodeList
    : [];

  if (areaCodeList.length === 0) {
    return ['未限制（全国）'];
  }

  return areaCodeList.map((code) => formatAdministrativeArea(code));
}

